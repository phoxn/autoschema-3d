// Крепёж: болт/гайка/винт
function bolt(id, name, sys, pos, ax, o = {}) {
  return {
    id, name, sys, pos, minor: true,
    shapes: [cyl(o.r ?? 0.007, o.h ?? 0.03, ax, o.c ?? STEEL)],
    tool: o.tool, removeOffset: o.off, label: o.label, desc: o.desc,
  };
}

