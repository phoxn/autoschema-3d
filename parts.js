const box = (s, c, p = [0, 0, 0], x = {}) => ({ t: 'box', s, c, p, ...x });
const cyl = (r, h, ax, c, p = [0, 0, 0], x = {}) => ({ t: 'cyl', r, h, ax, c, p, ...x });
const tube = (pts, r, c, x = {}) => ({ t: 'tube', pts, r, c, ...x });
